export function getLocale(language) {
  return language === 'en' ? 'en-US' : 'es-MX'
}

export function formatDate(date, language, options = {}) {
  return new Intl.DateTimeFormat(getLocale(language), {
    day: 'numeric',
    month: 'short',
    timeZone: 'UTC',
    ...options,
  }).format(new Date(`${date}T12:00:00Z`))
}

export function formatDateRange(startDate, endDate, language) {
  if (startDate === endDate) return formatDate(startDate, language)
  return `${formatDate(startDate, language)} — ${formatDate(endDate, language)}`
}
